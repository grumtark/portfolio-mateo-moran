/* ----------------------------------------------------------
   Motor i18n (proceso de diseñar y desarrollar software de modo que pueda adaptarse a diferentes idiomas, regiones y culturas sin necesidad de modificar el código fuente)
   ---------------------------------------------------------- */
(function () {
  "use strict";

  const STORAGE_KEY = "portfolio-lang";
  let currentLang = localStorage.getItem(STORAGE_KEY) || "es";

  /** Aplica el idioma a todos los elementos con [data-i18n] */
  function applyLang(lang) {
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;

    // Título de la página
    if (translations["meta.title"]) {
      document.title = translations["meta.title"][lang];
    }

    // Recorrer todos los nodos con data-i18n
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      const key = el.getAttribute("data-i18n");
      const entry = translations[key];
      if (!entry) return;

      const text = entry[lang];
      if (text === undefined) return;

      // Si el texto contiene HTML (spans internos, <br>), usar innerHTML
      if (text.includes("<")) {
        el.innerHTML = text;
      } else {
        el.textContent = text;
      }
    });

    // Actualizar el botón toggle
    const btn = document.getElementById("lang-toggle");
    if (btn) {
      btn.textContent = lang === "es" ? "EN" : "ES";
      btn.setAttribute("aria-label", lang === "es" ? "Switch to English" : "Cambiar a Español");
    }
  }

  /** Inicializa al cargar el DOM */
  document.addEventListener("DOMContentLoaded", function () {
    // Crear botón de toggle
    var btn = document.getElementById("lang-toggle");
    if (btn) {
      btn.addEventListener("click", function () {
        applyLang(currentLang === "es" ? "en" : "es");
      });
    }

    // Aplicar idioma guardado
    applyLang(currentLang);
  });
})();
